package gg.moonrise.engine.paper.gui.layout;

/**
 * Defines how matching layout keys should be ordered when used as paginated
 * content slots.
 */
public enum ContentSlotOrder {

    /**
     * Fill slots row by row from left to right.
     */
    HORIZONTAL,

    /**
     * Fill slots column by column from top to bottom.
     */
    VERTICAL
}
