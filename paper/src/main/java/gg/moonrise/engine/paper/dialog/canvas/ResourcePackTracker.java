package gg.moonrise.engine.paper.dialog.canvas;

import org.bukkit.entity.Player;
import org.bukkit.event.player.PlayerResourcePackStatusEvent;

import java.util.Collection;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Tracks which resource packs each player's client has actually applied.
 * <p>
 * Only {@link PlayerResourcePackStatusEvent.Status#SUCCESSFULLY_LOADED} counts as loaded; accepted or
 * downloaded packs are not applied yet. Fed by the engine's dialog listener, registered by {@code PaperPlugin}.
 */
public final class ResourcePackTracker {

    private final ConcurrentHashMap<UUID, Set<UUID>> loaded = new ConcurrentHashMap<>();

    /**
     * Records a pack status change.
     * @param playerId the player
     * @param packId the pack
     * @param status the new status
     */
    public void handle(UUID playerId, UUID packId, PlayerResourcePackStatusEvent.Status status) {
        Objects.requireNonNull(playerId, "playerId");
        Objects.requireNonNull(packId, "packId");
        Objects.requireNonNull(status, "status");

        switch (status) {
            case SUCCESSFULLY_LOADED -> markLoaded(playerId, packId);
            case ACCEPTED, DOWNLOADED -> {
            }
            default -> {
                Set<UUID> packs = loaded.get(playerId);
                if (packs != null) packs.remove(packId);
            }
        }
    }

    /**
     * Marks a pack as applied, for packs delivered outside Paper's status events.
     * @param playerId the player
     * @param packId the pack
     */
    public void markLoaded(UUID playerId, UUID packId) {
        loaded.computeIfAbsent(playerId, ignored -> ConcurrentHashMap.newKeySet()).add(packId);
    }

    /**
     * Returns whether a player has applied any of the given packs.
     * @param playerId the player
     * @param packIds acceptable packs
     * @return whether at least one of them is loaded
     */
    public boolean isLoaded(UUID playerId, Collection<UUID> packIds) {
        Set<UUID> packs = loaded.get(playerId);
        if (packs == null) return false;

        for (UUID packId : packIds) {
            if (packs.contains(packId)) return true;
        }
        return false;
    }

    /**
     * Returns whether a player has applied any server resource pack, for themes merged into a pack
     * whose id changes with every build, such as one generated by Nexo or ItemsAdder.
     * <p>
     * Also accepts the status Paper last recorded for the player, which covers packs applied before
     * this tracker saw any event.
     * @param player the player
     * @return whether a pack is loaded
     */
    public boolean isAnyLoaded(Player player) {
        Set<UUID> packs = loaded.get(player.getUniqueId());
        if (packs != null && !packs.isEmpty()) return true;

        return player.getResourcePackStatus() == PlayerResourcePackStatusEvent.Status.SUCCESSFULLY_LOADED;
    }

    /**
     * Returns the packs a player has applied.
     * @param playerId the player
     * @return a snapshot of the loaded pack ids
     */
    public Set<UUID> loadedPacks(UUID playerId) {
        Set<UUID> packs = loaded.get(playerId);
        return packs == null ? Set.of() : Set.copyOf(packs);
    }

    /**
     * Forgets a player, for example when they leave.
     * @param playerId the player
     */
    public void forget(UUID playerId) {
        loaded.remove(playerId);
    }
}
